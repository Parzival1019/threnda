"""UserSession — a server-side record of one logged-in browser/API session.

The session identifier a client holds (the ``threnda_session`` cookie, or a
bearer token for the API) is a high-entropy random value generated by
``threnda.app.services.auth.create_session``. Only its SHA-256 hash is
stored here (``token_hash``) — the plaintext value is never persisted
anywhere, so a database read (backup, dump, replication lag snapshot)
cannot be used to impersonate a user, mirroring how passwords are never
stored in recoverable form either.

Hashing the token with a fast, unsalted digest (rather than Argon2, as for
passwords) is deliberate and standard practice for this kind of secret: the
token is already 256 bits of CSPRNG output, so it has no guessable
structure for a slow, salted KDF to defend against — the only question is
whether an attacker who has *already* read this table can compute the
value a client would send, which SHA-256's preimage resistance already
answers no to. See docs/security.md, "Sessions".
"""

from __future__ import annotations

from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import ForeignKey, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from threnda.app.db.base import Base
from threnda.app.models.mixins import utcnow
from threnda.app.models.types import UTCDateTime

if TYPE_CHECKING:
    from threnda.app.models.user import User


class UserSession(Base):
    __tablename__ = "user_sessions"

    id: Mapped[int] = mapped_column(primary_key=True)
    user_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    # SHA-256 hex digest (64 hex characters) of the opaque session token.
    token_hash: Mapped[str] = mapped_column(String(64), nullable=False, unique=True, index=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime(), default=utcnow, nullable=False)
    last_seen_at: Mapped[datetime] = mapped_column(UTCDateTime(), default=utcnow, nullable=False)
    # Absolute expiry — a hard cap regardless of activity. Idle expiry is
    # enforced separately in threnda.app.services.auth against
    # last_seen_at, so a session can become invalid before this too.
    expires_at: Mapped[datetime] = mapped_column(UTCDateTime(), nullable=False)
    revoked_at: Mapped[datetime | None] = mapped_column(UTCDateTime(), nullable=True)
    user_agent: Mapped[str | None] = mapped_column(String(300), nullable=True)
    ip_address: Mapped[str | None] = mapped_column(String(64), nullable=True)

    user: Mapped[User] = relationship(back_populates="sessions")

    def __repr__(self) -> str:  # pragma: no cover - debugging aid only
        return f"UserSession(id={self.id!r}, user_id={self.user_id!r})"
